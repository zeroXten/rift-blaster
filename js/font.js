const CELL = 6, GH = 7;
const chars = Object.keys(G);
const index = new Map(chars.map((c, i) => [c, i]));
const atlases = new Map();
let ctx = null;

export function initFont(context) { ctx = context; }

function atlas(color) {
  let a = atlases.get(color);
  if (!a) {
    a = document.createElement('canvas');
    a.width = chars.length * CELL;
    a.height = GH;
    const g = a.getContext('2d');
    g.fillStyle = color;
    chars.forEach((ch, i) => G[ch].split('/').forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') g.fillRect(i * CELL + x, y, 1, 1);
    }));
    atlases.set(color, a);
  }
  return a;
}

export function textWidth(str, scale = 1) {
  return (String(str).length * CELL - 1) * scale;
}

// align: 0 left, 0.5 centre, 1 right.
export function drawText(str, x, y, color = '#f4f4f4', scale = 1, align = 0) {
  str = String(str).toUpperCase();
  const a = atlas(color);
  x = Math.round(x - textWidth(str, scale) * align);
  y = Math.round(y);
  for (let i = 0; i < str.length; i++) {
    const gi = index.get(str[i]);
    if (gi !== undefined) ctx.drawImage(a, gi * CELL, 0, 5, GH, x + i * CELL * scale, y, 5 * scale, GH * scale);
  }
}

// With a drop shadow, for text over the camera feed.
export function drawTextS(str, x, y, color, scale = 1, align = 0) {
  drawText(str, x + scale, y + scale, '#05050a', scale, align);
  drawText(str, x, y, color, scale, align);
}

export function wrapText(str, max) {
  const out = [];
  for (const para of String(str).split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (line && (line + ' ' + word).length > max) { out.push(line); line = word; }
      else line = line ? line + ' ' + word : word;
    }
    out.push(line);
  }
  return out;
}
